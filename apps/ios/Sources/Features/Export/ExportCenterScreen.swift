    /// it passes `nil` and the "Export again" button is hidden. The advanced builder passes a
    /// closure to re-run the same scope+format.
    var onRunAgain: (() -> Void)?

    @State private var copiedValue: String?

    private var checksums: [String: String] { result.job.manifest?.checksums ?? [:] }

    var body: some View {
        BadanCard {
            VStack(alignment: .leading, spacing: BadanSpace.space3) {
                HStack(spacing: BadanSpace.space2) {
                    Image(systemName: "checkmark.seal.fill")
                        .imageScale(.large)
                        .foregroundStyle(BadanColor.inBand)
                        .accessibilityHidden(true)
                    Text(ExportCopy.exportReady, language: env.language)
                        .font(BadanFont.body.weight(.semibold))
                        .foregroundStyle(BadanColor.textPrimary)
                    Spacer(minLength: BadanSpace.space2)
                    if result.job.manifest?.encrypted == true {
                        PillLabel(env.s(ExportCopy.encryptedBadge), systemImage: "lock.fill", tint: BadanColor.primary)
                    }
                    PillLabel(result.job.format.rawValue.uppercased(), tint: BadanColor.primary)
