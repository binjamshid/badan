/// The offered windows. Maps to `ExportScope.startDate`/`endDate`; "all time" leaves both open,
/// "custom" reads two user-picked dates instead of a fixed offset.
///
/// Not `private` — `String` raw values make this the round-trip type for the remembered-range
/// side of STUB-06b (`sessionPreferences.lastExportRange`), and `SessionExportMemory`'s mapping
/// helper needs to be directly testable from `SessionPrefsFixTests`.
enum ExportRange: String, CaseIterable, Hashable {
    case last30, last90, all, custom

    func startDate(now: Date) -> Date? {
        switch self {
        case .last30: return now.addingTimeInterval(-30 * 86_400)
        case .last90: return now.addingTimeInterval(-90 * 86_400)
        case .all, .custom: return nil
        }
    }

    func label(_ format: ValueFormatter) -> LocalizedString {
        switch self {
        case .last30:
            let n = format.integer(30)
            return LocalizedString(en: "Last \(n) days", ar: "آخر \(n) يوماً")
        case .last90:
            let n = format.integer(90)
            return LocalizedString(en: "Last \(n) days", ar: "آخر \(n) يوماً")
        case .all:
            return LocalizedString(en: "All time", ar: "كل الوقت")
        case .custom:
            return LocalizedString(en: "Custom", ar: "مخصص")
        }
    }
}

/// Read side of the export session memory (STUB-06b) — `CustomizationProfile.sessionPreferences`
/// stores `lastExportFormat`/`lastExportRange` as raw strings (so the model doesn't need to know
/// about this screen's own enums), so both mappings tolerate a `nil`, unrecognized, or
/// since-removed raw value by falling back to the caller-supplied current default rather than
/// crashing or silently producing a wrong format/range.
enum SessionExportMemory {
    static func rememberedFormat(_ raw: String?, fallback: ExportFormat) -> ExportFormat {
        guard let raw, let format = ExportFormat(rawValue: raw) else { return fallback }
        return format
    }

    static func rememberedRange(_ raw: String?, fallback: ExportRange) -> ExportRange {
        guard let raw, let range = ExportRange(rawValue: raw) else { return fallback }
        return range
    }
}

// MARK: - View model

/// A past export paired with the file URLs actually still reachable on disk, resolved once
/// (not per render — PERF-083) from the job's own manifest.
struct ExportHistoryItem: Identifiable {
    let job: ExportJob
    let fileURLs: [URL]
    var id: String { job.id }
}

/// One completed run, paired with its manifest's metric-id keys sorted once (PERF-085) instead
/// of on every render of the detail view.
struct ExportResultDisplay: Identifiable {
    let result: ExportRunner.ExportResult
    let sortedMetricIds: [String]
    var id: String { result.job.id }
}

@Observable
@MainActor
final class ExportCenterViewModel {
    var history: [ExportHistoryItem] = []
    var lastResults: [ExportResultDisplay] = []
    var isRunning = false
    var errorText: String?
    /// Set when the last run's window was clipped by the D-33 free-export cap. The builder renders
    /// it beside the success card; the same sentence Quick Export and the Shortcut path use, because
    /// one limit deserves one wording (`ExportCopy.clampedToFreeWindow`).
    var notice: LocalizedString?

    func loadHistory(_ env: AppEnvironment) {
        // Reconcile any job an interrupted app session left stuck `pending`/`running` — screen-
        // load is the only hook available here (this view model can't reach into app startup)
        // (EDGE-02a).
        try? env.exportJobs.markStaleRunningAsFailed()
        history = Self.buildItems(from: (try? env.exportJobs.recent(limit: 20)) ?? [])
    }

    static func buildItems(from jobs: [ExportJob]) -> [ExportHistoryItem] {
        jobs.map { ExportHistoryItem(job: $0, fileURLs: availableFileURLs(for: $0)) }
    }

    /// Rebuilds shareable file URLs for a persisted job. Filenames come from the manifest's own
    /// checksum keys — the only source of truth for what was actually written. A job whose
    /// manifest is missing or empty (e.g. failed to decode after a future schema change) is
    /// treated as unverifiable and offers nothing to re-share rather than guessing filenames
    /// (OPT-139): re-sharing a file we can no longer verify against its own manifest would
    /// undermine the manifest's entire tamper-evidence purpose. Only files still on disk are
    /// offered.
    static func availableFileURLs(for job: ExportJob) -> [URL] {
        guard let path = job.outputPath, let manifest = job.manifest, !manifest.checksums.isEmpty else { return [] }
        let folder = URL(fileURLWithPath: path, isDirectory: true)
        // An encrypted job's plaintext files no longer exist on disk (deleted the moment
        // `ExportRunner.encryptResult` wrote the container, ledger #19) — the one shareable
        // artifact is the container itself, named on the manifest rather than assumed, so this
        // stays correct even if `ExportEncryptor.containerFileName` ever changes.
        if manifest.encrypted, let containerName = manifest.encryptedContainerName {
            let containerURL = folder.appendingPathComponent(containerName)
            return FileManager.default.fileExists(atPath: containerURL.path) ? [containerURL] : []
        }
        var names = Array(manifest.checksums.keys)
        if job.format == .csv { names.append("manifest.json") }
        return names
            .map { folder.appendingPathComponent($0) }
            .filter { FileManager.default.fileExists(atPath: $0.path) }
    }

    /// Runs one export per requested format, sequentially, off the main actor (`ExportRunner` is
    /// fully synchronous, offline, and thread-safe — SQLite recursive lock) so a large "all
    /// time · raw+derived" export never freezes the UI or risks the iOS watchdog; then hops back
    /// to update state once. A failure aborts any remaining formats, matching the previous
    /// single-format error behavior.
    /// `passphrase` is only used (and only meaningful) when `scope.includeSensitive` is true —
    /// `AdvancedExportBuilderScreen` gates the Run button so a sensitive scope can't reach here
    /// without a passphrase already validated against `ExportPassphrasePolicy`, and `ExportRunner`
    /// itself enforces the same rule again as a second line of defense (review ledger #19,
    /// deferred fix 3 / FEAT-185; ADR-0008).
    ///
    /// D-33 applies here. This is the Advanced Export Builder's Run button — a user-facing export
    /// whose artifacts leave BADAN through the share sheet — so it is capped by the same free window
    /// as Quick Export and the Shortcut path. It was the third surface found running unclamped: the
    /// builder honours the user's "All time" or custom range verbatim, and `runAdHoc` passed no
    /// entitlement, so a trial-expired user got their whole history from a screen one tap away from
    /// the hub that would have returned seven days. CLAMPED, never refused — viewing, keeping and
    /// logging stay free and uncapped forever (D-33), and only the bulk file is narrowed — and never
    /// silently: `wasNarrowed` is recomputed here purely to raise the notice, since the clamp itself
    /// belongs to `ExportRunner.run` and must have exactly one implementation.
    func run(scope: ExportScope, formats: [ExportFormat], env: AppEnvironment, passphrase: String? = nil) {
        guard !isRunning, !formats.isEmpty else { return }
        isRunning = true
        errorText = nil
        notice = nil
        lastResults = []
        try? env.exportJobs.markStaleRunningAsFailed()
        let exporter = env.exporter
        // Read the entitlement on the main actor before hopping off it, matching
        // `ExportManageService.runResolved`.
        let entitlement = env.subscription.policyState
        let wasNarrowed = SubscriptionPolicy.clampExportScope(scope, state: entitlement,
                                                             now: env.now()).wasNarrowed
        Task {
            do {
                var produced: [ExportResultDisplay] = []
                for fmt in formats {
                    // (BUG-EXPORT-P1a) `runAdHoc`, not `run`: the ad-hoc builder export must land
                    // in the `ExportRun` ledger like every other export surface, or Export Health
                    // reports this successful run as a probable mid-export crash. See `runAdHoc`'s doc.
                    let result = try await Task.detached(priority: .userInitiated) {
                        try exporter.runAdHoc(scope: scope, format: fmt, passphrase: passphrase,
                                              entitlement: entitlement)
                    }.value
                    let sortedIds = result.job.manifest?.perMetricRowCounts.keys.sorted() ?? []
                    produced.append(ExportResultDisplay(result: result, sortedMetricIds: sortedIds))
                }
                lastResults = produced
                // Say what the file actually covers. A clipped export that looks complete is worse
                // than no cap at all — the reader would have no way to know rows are missing.
                notice = wasNarrowed ? ExportCopy.clampedToFreeWindow : nil
                loadHistory(env)
            } catch {
                errorText = String(describing: error)
            }
            isRunning = false
        }
    }
}

